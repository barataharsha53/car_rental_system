class Car {
  final String name;
  final String type;
  final String category;
  final String image;
  final int price;
  final int seats;
  final String fuel;
  final String transmission;

  Car({
    required this.name,
    required this.type,
    required this.category,
    required this.image,
    required this.price,
    required this.seats,
    required this.fuel,
    required this.transmission,
  });
}
